class Report:
    def __init__(self, step):
        self.step = step
        self.lines = []
        self.failures = []
        os.makedirs(os.path.join(ROOT, "analysis", "raw"), exist_ok=True)
        self.logf = open(os.path.join(ROOT, "analysis", "raw", f"probe_{step}.log"), "w", encoding="utf-8")

    def log(self, msg):
        print(msg)
        self.logf.write(msg + "\n")

    def quiet(self, msg):
        self.logf.write(msg + "\n")

    def md(self, line=""):
        self.lines.append(line)

    def check(self, ok, what):
        self.log(("PASS  " if ok else "FAIL  ") + what)
        self.md(f"- {'✅' if ok else '❌'} {what}")
        if not ok:
            self.failures.append(what)

    def save(self, title):
        path = os.path.join(ROOT, "analysis", f"probe_{self.step}.md")
        head = [f"# Probe {self.step}: {title}", "",
                f"Generated by `tools/probe/probe.py {self.step}` on {time.strftime('%Y-%m-%d %H:%M')}.",
                f"Result: **{'PASS' if not self.failures else 'FAIL'}**", ""]
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(head + self.lines) + "\n")
        self.log(f"report -> {os.path.relpath(path, ROOT)}")
        self.logf.close()
        return 0 if not self.failures else 1


def build(so, rep, install_hle=False):
    emu = E.Emu(so, log=rep.log)
    if install_hle:
        import hle_libc
        hle_libc.install(emu, rep)
    stats = emu.load()
    return emu, stats


