"""Phase 1 boot probe for libGangster2.so.

  python -I tools/probe/probe.py 1a     # load + relocate + verify (no execution)
  python -I tools/probe/probe.py 1b     # run the DT_INIT_ARRAY constructors
  python -I tools/probe/probe.py 1c     # first JNI calls with a fake JNIEnv

Reports go to analysis/probe_<step>.md (small, committed) and full logs to
analysis/raw/probe_<step>.log (git-ignored).
"""
import argparse
import collections
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)  # our own modules only (we run with python -I)

from elftools.elf.relocation import RelocationSection  # noqa: E402

import emu as E  # noqa: E402
from elfimage import R_ARM_GLOB_DAT, R_ARM_JUMP_SLOT, demangle  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
DEFAULT_SO = os.path.join(ROOT, "work", "apk", "lib", "armeabi", "libGangster2.so")
DEFAULT_DATA = os.path.join(ROOT, "original", "gameloft", "games", "Gangstar2")


class Report:
    def __init__(self, step):
        self.step = step
        self.lines = []
        self.failures = []
        os.makedirs(os.path.join(ROOT, "analysis", "raw"), exist_ok=True)
        self.logf = open(os.path.join(ROOT, "analysis", "raw", f"probe_{step}.log"), "w", encoding="utf-8")

    def log(self, msg):
        print(msg)
        self.logf.write(msg + "\n")

    def quiet(self, msg):
        self.logf.write(msg + "\n")

    def md(self, line=""):
        self.lines.append(line)

    def check(self, ok, what):
        self.log(("PASS  " if ok else "FAIL  ") + what)
        self.md(f"- {'✅' if ok else '❌'} {what}")
        if not ok:
            self.failures.append(what)

    def save(self, title):
        path = os.path.join(ROOT, "analysis", f"probe_{self.step}.md")
        head = [f"# Probe {self.step}: {title}", "",
                f"Generated by `tools/probe/probe.py {self.step}` on {time.strftime('%Y-%m-%d %H:%M')}.",
                f"Result: **{'PASS' if not self.failures else 'FAIL'}**", ""]
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(head + self.lines) + "\n")
        self.log(f"report -> {os.path.relpath(path, ROOT)}")
        self.logf.close()
        return 0 if not self.failures else 1


def build(so, rep, install_hle=False):
    emu = E.Emu(so, log=rep.log)
    if install_hle:
        import hle_libc
        hle_libc.install(emu, rep)
    stats = emu.load()
    return emu, stats


# ---------------------------------------------------------------------------
def step_1a(args):
    rep = Report("1a")
    emu, stats = build(args.so, rep)
    lib = emu.lib
    d = lib.dynamic
    rep.md("## Relocations")
    rep.md("")
    for k, v in sorted(stats.items()):
        rep.md(f"- {k}: {v:,}")
    rep.md("")
    rep.md("## Checks")
    rep.md("")

    n_rel = d["DT_RELSZ"] // d["DT_RELENT"]
    n_plt = d["DT_PLTRELSZ"] // 8
    rep.check(stats["R_ARM_RELATIVE"] == d["DT_RELCOUNT"] == 43374,
              f"R_ARM_RELATIVE applied = {stats['R_ARM_RELATIVE']:,} = DT_RELCOUNT ({d['DT_RELCOUNT']:,})")
    rep.check(stats["R_ARM_RELATIVE"] + stats["R_ARM_ABS32"] + stats["R_ARM_GLOB_DAT"] == n_rel,
              f".rel.dyn entries applied = {n_rel:,} (DT_RELSZ/DT_RELENT); ABS32={stats['R_ARM_ABS32']:,}, GLOB_DAT={stats['R_ARM_GLOB_DAT']}")
    rep.check(stats["R_ARM_JUMP_SLOT"] == n_plt == 290,
              f"R_ARM_JUMP_SLOT applied = {stats['R_ARM_JUMP_SLOT']} = DT_PLTRELSZ/8 ({n_plt})")

    n_imports = len(lib.imports)
    n_traps = len(emu.traps) - 1  # minus the return sentinel
    n_data = sum(1 for s in lib.imports if s.name in emu.data)
    unbound = sorted(s.name for s in lib.imports if s.name not in emu.trap_addr and s.name not in emu.data)
    rep.check(n_traps + n_data + len(unbound) == n_imports == 299 and not emu.unresolved
              and unbound == ["__aeabi_unwind_cpp_pr0", "__aeabi_unwind_cpp_pr1"],
              f"{n_imports} imports: {n_traps} function traps + {n_data} bionic data objects bound; "
              f"{len(unbound)} never referenced by any relocation ({', '.join(unbound)}: only named by .ARM.exidx)")

    # GOT slots point where they should
    bad = []
    for sec in lib.elf.iter_sections():
        if not isinstance(sec, RelocationSection):
            continue
        for r in sec.iter_relocations():
            t = r["r_info_type"]
            if t not in (R_ARM_GLOB_DAT, R_ARM_JUMP_SLOT):
                continue
            v = lib.u32(r["r_offset"])
            sym = lib.dynsyms[r["r_info_sym"]]
            in_trap = E.TRAP_BASE <= v < E.TRAP_BASE + E.TRAP_SIZE
            in_data = E.DATA_BASE <= v < E.DATA_BASE + E.DATA_SIZE
            in_lib = E.LIB_BASE <= v < E.LIB_BASE + lib.size
            ok = (in_trap if t == R_ARM_JUMP_SLOT else (in_trap or in_data)) if sym["st_shndx"] == "SHN_UNDEF" else in_lib
            if not ok:
                bad.append((r["r_offset"], sym.name, v))
    rep.check(not bad, f"every JUMP_SLOT/GLOB_DAT slot points at a trap, a data object or the library ({len(bad)} bad)")
    for off, name, v in bad[:10]:
        rep.log(f"      slot {off:#x} {name} = {v:#x}")

    # init_array entries are function starts with the right Thumb bit
    ia = lib.init_array()
    bad_ia = []
    for v in ia:
        rel = v - E.LIB_BASE
        info = lib.func_start(rel & ~1)
        if info is None or (lib.funcs[info[0]] & 1) != (v & 1):
            bad_ia.append(v)
    rep.check(len(ia) == 448 and not bad_ia,
              f"{len(ia)} DT_INIT_ARRAY entries all point at function starts with matching ARM/Thumb bit ({len(bad_ia)} bad)")

    # vtables: every slot must be explainable after relocation
    typeinfos = {v for n, (v, _) in lib.objects.items() if n.startswith("_ZTI")}
    trap_names = {a: n for n, a in emu.trap_addr.items()}
    cats = collections.Counter()
    unexplained = []
    vtables = [(n, v, s) for n, (v, s) in lib.objects.items() if n.startswith("_ZTV") and s >= 8]
    for name, start, size in vtables:
        for i in range(size // 4):
            v = lib.u32(start + 4 * i)
            sv = v - (1 << 32) if v & 0x80000000 else v
            if v == 0:
                cats["zero"] += 1
            elif v in trap_names:
                cats["import:" + trap_names[v]] += 1
            elif E.LIB_BASE <= v < E.LIB_BASE + lib.size:
                rel = v - E.LIB_BASE
                info = lib.func_start(rel & ~1)
                if info is not None and (lib.funcs[info[0]] & 1) == (v & 1):
                    cats["function"] += 1
                elif rel in typeinfos:
                    cats["typeinfo"] += 1
                else:
                    unexplained.append((name, i, v))
            elif abs(sv) < 0x100000:
                cats["offset (offset-to-top / vbase)"] += 1
            else:
                unexplained.append((name, i, v))
    total = sum(cats.values()) + len(unexplained)
    rep.check(len(vtables) > 20 and not unexplained,
              f"{len(vtables):,} C++ vtables, {total:,} slots: every slot is a function start, typeinfo, import, 0 or small offset ({len(unexplained)} unexplained)")
    for k, v in cats.most_common():
        rep.md(f"    - {k}: {v:,}")
    for name, i, v in unexplained[:15]:
        rep.log(f"      {demangle(name)}[{i}] = {v:#x} ({emu.where(v)})")

    # the mapped memory equals the relocated image
    same = emu.read(E.LIB_BASE, lib.size) == bytes(lib.image)
    rep.check(same, f"Unicorn memory at {E.LIB_BASE:#x} equals the relocated image ({lib.size:,} bytes)")

    # spot check: a function we disassembled in Phase 0 is where we expect it
    a = emu.func("Java_com_gameloft_android_GAND_GloftGMHP_ML_GameRenderer_nativeGetJNIEnv")
    head = emu.read(a & ~1, 12).hex()
    rep.check(a == E.LIB_BASE + 0x368db9 and head.startswith("024b034a7b44"),
              f"nativeGetJNIEnv at {a:#x}: bytes {head} (ldr r3,[pc,#8]; ldr r2,[pc,#12]; add r3,pc ...)")
    return rep.save("load + relocate libGangster2.so")


def watch_ctype(emu):
    w = {}
    for name in ("_ctype_", "_tolower_tab_", "_toupper_tab_"):
        w[name] = emu.watch(name, emu.data[name], 4)
        w[name + "#table"] = emu.watch(name + "#table", emu.data[name + "#table"], 257 * 2)
    return w


def ctype_findings(emu, w):
    out = []
    for name in ("_ctype_", "_tolower_tab_", "_toupper_tab_"):
        p, t = w[name], w[name + "#table"]
        if not p and not t:
            out.append(f"`{name}`: not read yet")
            continue
        ptr_ok = all(off == 0 and sz == 4 for off, sz, _ in p)
        out.append(f"`{name}`: {len(p)} reads of the 4-byte pointer object "
                   f"({'all aligned 32-bit loads' if ptr_ok else 'UNEXPECTED access pattern'}), "
                   f"{len(t)} reads of the table it points to"
                   + (f"; first reader {emu.where(p[0][2])}" if p else ""))
    return out


def run_constructors(emu, rep):
    ia = emu.lib.init_array()
    per = []
    for i, f in enumerate(ia):
        before = collections.Counter(emu.calls)
        try:
            emu.call(f)
        except (E.ProbeError, E.GuestExit) as exc:
            rep.log(f"constructor #{i} at {emu.where(f)} FAILED:\n{exc}")
            return i, per
        delta = collections.Counter(emu.calls)
        delta.subtract(before)
        per.append((i, f, +delta))
    return len(ia), per


def step_1b(args):
    rep = Report("1b")
    emu, _ = build(args.so, rep, install_hle=True)
    w = watch_ctype(emu)
    t0 = time.time()
    done, per = run_constructors(emu, rep)
    dt = time.time() - t0
    total = len(emu.lib.init_array())
    rep.md("## Checks")
    rep.md("")
    rep.check(done == total == 448, f"{done}/{total} DT_INIT_ARRAY constructors ran and returned ({dt:.1f} s)")
    rep.check(not emu.threads, f"no threads started during static init ({len(emu.threads)})")
    stubbed = sorted(emu.stubbed)
    rep.check(True, f"imports hit that are still plain stubs: {', '.join(stubbed) if stubbed else 'none'}")

    rep.md("")
    rep.md("## What static initialisation does")
    rep.md("")
    used = [(n, emu.calls[n]) for n in emu.call_order]
    rep.md(f"- constructors that call any import: {sum(1 for _, _, d in per if d)} of {done}")
    rep.md(f"- sbrk heap in use afterwards: {emu.brk - E.SBRK_BASE:,} bytes ({emu.sbrk_calls} sbrk calls)")
    rep.md(f"- destructors registered via `__aeabi_atexit`: {len(emu.atexit)}")
    rep.md(f"- file-system events: {len(emu.fs_events)}")
    for ev in emu.fs_events[:20]:
        rep.md(f"    - {ev}")
    rep.md("")
    rep.md("### Imports called (first-use order)")
    rep.md("")
    rep.md("| import | calls | handled by |")
    rep.md("|---|---:|---|")
    for n, c in used:
        rep.md(f"| `{n}` | {c:,} | {'STUB' if n in emu.stubbed else 'HLE'} |")
    rep.md("")
    rep.md("### Heaviest constructors (by import calls)")
    rep.md("")
    for i, f, d in sorted(per, key=lambda x: -sum(x[2].values()))[:10]:
        if d:
            top = ", ".join(f"{k}×{v}" for k, v in d.most_common(4))
            rep.md(f"- #{i} `{emu.where(f)}`: {sum(d.values()):,} calls ({top})")
    rep.md("")
    rep.md("### bionic ctype layout check")
    rep.md("")
    for line in ctype_findings(emu, w):
        rep.md(f"- {line}")
    for line in ctype_findings(emu, w):
        rep.log(line)
    return rep.save("run the 448 static constructors")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["1a", "1b", "1c"])
    ap.add_argument("--so", default=DEFAULT_SO)
    ap.add_argument("--data", default=DEFAULT_DATA)
    args = ap.parse_args()
    fn = {"1a": step_1a, "1b": step_1b}.get(args.step)
    if fn is None:
        print(f"step {args.step} not implemented yet")
        return 2
    return fn(args)


if __name__ == "__main__":
    sys.exit(main())
