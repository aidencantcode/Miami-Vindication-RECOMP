"""Assemble src/cpu/fastpath.S (ARM, armv7ve + VFPv4) with Visual Studio's clang and
emit src/cpu/fastpath_code.inc (machine code bytes + symbol offsets) for the runtime.
Also prints a capstone disassembly so the encodings can be eyeballed.

Usage: python -I tools/gen_fastpath.py
"""
import glob
import os
import subprocess
import sys

from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM
from elftools.elf.elffile import ELFFile

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "src", "cpu", "fastpath.S")
OBJ = os.path.join(ROOT, "build", "fastpath.o")
OUT = os.path.join(ROOT, "src", "cpu", "fastpath_code.inc")

clang = (glob.glob(r"C:\Program Files\Microsoft Visual Studio\*\*\VC\Tools\Llvm\x64\bin\clang.exe") or [None])[0]
if not clang:
    sys.exit("clang.exe from Visual Studio not found")
os.makedirs(os.path.dirname(OBJ), exist_ok=True)
subprocess.run([clang, "--target=armv7a-none-eabi", "-mcpu=cortex-a15", "-marm", "-c", SRC, "-o", OBJ], check=True)

elf = ELFFile(open(OBJ, "rb"))
text = elf.get_section_by_name(".text").data()
syms = sorted((s["st_value"], s.name) for s in elf.get_section_by_name(".symtab").iter_symbols()
              if s["st_info"]["type"] == "STT_FUNC")
rel = elf.get_section_by_name(".rel.text")
if rel is not None and rel.num_relocations():
    sys.exit("fastpath code must be position independent (found relocations)")

md = Cs(CS_ARCH_ARM, CS_MODE_ARM)
names = dict((v, n) for v, n in syms)
for ins in md.disasm(text, 0):
    if ins.address in names:
        print(f"{names[ins.address]}:")
    print(f"   {ins.address:04x}  {ins.mnemonic:8s} {ins.op_str}")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("// GENERATED by tools/gen_fastpath.py from src/cpu/fastpath.S - do not edit.\n")
    fh.write(f"static const unsigned char kFastpathCode[{len(text)}] = {{\n")
    for i in range(0, len(text), 16):
        fh.write("    " + ", ".join(f"0x{b:02x}" for b in text[i:i + 16]) + ",\n")
    fh.write("};\n")
    fh.write("static const struct { const char* name; unsigned offset; } kFastpathSyms[] = {\n")
    for v, n in syms:
        fh.write(f'    {{"{n}", 0x{v:x}}},\n')
    fh.write("};\n")
print(f"{len(syms)} helpers, {len(text)} bytes -> {OUT}")
